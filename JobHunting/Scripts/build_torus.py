import math
import os

import unreal


BLUEPRINT_DIR = "/Game/ThirdPerson/Blueprints"
MESH_NAME = "SM_Torus"
MESH_PATH = "{}/{}".format(BLUEPRINT_DIR, MESH_NAME)
TORUS_BP_NAME = "BP_Torus"
TORUS_BP_PATH = "{}/{}".format(BLUEPRINT_DIR, TORUS_BP_NAME)
CHARACTER_BP_PATH = "/Game/ThirdPerson/Blueprints/BP_ThirdPersonCharacter1"
MATERIAL_PATH = "/Engine/BasicShapes/BasicShapeMaterial"

# Torus shape (cm). The ring lies flat like a halo.
MAJOR_RADIUS = 30.0
MINOR_RADIUS = 5.0
MAJOR_SEGMENTS = 32
MINOR_SEGMENTS = 12

RING_COMPONENT_NAME = "Ring"
CHILD_COMPONENT_NAME = "Torus"
# Gap between the top of the capsule and the ring.
HEAD_CLEARANCE = 15.0


def write_torus_obj(path):
    lines = ["# Torus generated by build_torus.py"]
    for i in range(MAJOR_SEGMENTS):
        u = 2.0 * math.pi * i / MAJOR_SEGMENTS
        for j in range(MINOR_SEGMENTS):
            v = 2.0 * math.pi * j / MINOR_SEGMENTS
            nx, ny, nz = math.cos(v) * math.cos(u), math.cos(v) * math.sin(u), math.sin(v)
            x = (MAJOR_RADIUS + MINOR_RADIUS * math.cos(v)) * math.cos(u)
            y = (MAJOR_RADIUS + MINOR_RADIUS * math.cos(v)) * math.sin(u)
            z = MINOR_RADIUS * math.sin(v)
            lines.append("v {:.4f} {:.4f} {:.4f}".format(x, y, z))
            lines.append("vn {:.4f} {:.4f} {:.4f}".format(nx, ny, nz))
    for i in range(MAJOR_SEGMENTS):
        for j in range(MINOR_SEGMENTS):
            a = i * MINOR_SEGMENTS + j + 1
            b = ((i + 1) % MAJOR_SEGMENTS) * MINOR_SEGMENTS + j + 1
            c = ((i + 1) % MAJOR_SEGMENTS) * MINOR_SEGMENTS + (j + 1) % MINOR_SEGMENTS + 1
            d = i * MINOR_SEGMENTS + (j + 1) % MINOR_SEGMENTS + 1
            lines.append("f {0}//{0} {1}//{1} {2}//{2} {3}//{3}".format(a, b, c, d))
    with open(path, "w") as obj_file:
        obj_file.write("\n".join(lines) + "\n")


def import_torus_mesh():
    if unreal.EditorAssetLibrary.does_asset_exist(MESH_PATH):
        unreal.log("{} already exists, reusing it".format(MESH_PATH))
        return unreal.EditorAssetLibrary.load_asset(MESH_PATH)

    obj_path = os.path.join(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_intermediate_dir()), MESH_NAME + ".obj")
    write_torus_obj(obj_path)

    task = unreal.AssetImportTask()
    task.filename = obj_path
    task.destination_path = BLUEPRINT_DIR
    task.destination_name = MESH_NAME
    task.automated = True
    task.replace_existing = True
    task.save = True
    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks([task])

    for imported_path in task.imported_object_paths:
        asset = unreal.load_asset(imported_path)
        if isinstance(asset, unreal.StaticMesh):
            return asset
    raise RuntimeError("Could not import the torus mesh from {}".format(obj_path))


def fit_ring_transform(mesh):
    # Importers may swap axes or units, so measure the result: the thinnest axis must become Z.
    bounds = mesh.get_bounding_box()
    size = bounds.max - bounds.min
    extents = {"x": size.x, "y": size.y, "z": size.z}
    thin_axis = min(extents, key=extents.get)
    rotation = {
        "x": unreal.Rotator(roll=0.0, pitch=90.0, yaw=0.0),
        "y": unreal.Rotator(roll=90.0, pitch=0.0, yaw=0.0),
        "z": unreal.Rotator(roll=0.0, pitch=0.0, yaw=0.0),
    }[thin_axis]
    diameter = max(value for axis, value in extents.items() if axis != thin_axis)
    scale = (2.0 * (MAJOR_RADIUS + MINOR_RADIUS)) / diameter if diameter > 0 else 1.0
    return rotation, unreal.Vector(scale, scale, scale)


def add_component(blueprint, parent_handle, component_class, name):
    params = unreal.AddNewSubobjectParams(
        parent_handle=parent_handle,
        new_class=component_class,
        blueprint_context=blueprint,
    )
    handle, _ = SUBOBJECT_SUBSYSTEM.add_new_subobject(params)
    if not unreal.SubobjectDataBlueprintFunctionLibrary.is_handle_valid(handle):
        raise RuntimeError("Could not add component {}".format(name))
    SUBOBJECT_SUBSYSTEM.rename_subobject(handle, unreal.Text(name))
    data = unreal.SubobjectDataBlueprintFunctionLibrary.get_data(handle)
    return unreal.SubobjectDataBlueprintFunctionLibrary.get_object(data)


def find_component_handle(blueprint, predicate):
    for handle in SUBOBJECT_SUBSYSTEM.k2_gather_subobject_data_for_blueprint(blueprint):
        data = unreal.SubobjectDataBlueprintFunctionLibrary.get_data(handle)
        component = unreal.SubobjectDataBlueprintFunctionLibrary.get_object(data)
        if component and predicate(component):
            return handle
    return None


def create_torus_blueprint(mesh):
    # Never recreate an existing asset: that would wipe edits made in the editor.
    if unreal.EditorAssetLibrary.does_asset_exist(TORUS_BP_PATH):
        unreal.log("{} already exists, reusing it".format(TORUS_BP_PATH))
        return unreal.EditorAssetLibrary.load_asset(TORUS_BP_PATH)

    factory = unreal.BlueprintFactory()
    factory.set_editor_property("parent_class", unreal.Actor)
    blueprint = unreal.AssetToolsHelpers.get_asset_tools().create_asset(
        TORUS_BP_NAME, BLUEPRINT_DIR, unreal.Blueprint, factory
    )
    if not blueprint:
        raise RuntimeError("Could not create {}".format(TORUS_BP_PATH))

    root_handle = SUBOBJECT_SUBSYSTEM.k2_gather_subobject_data_for_blueprint(blueprint)[0]
    ring = add_component(blueprint, root_handle, unreal.StaticMeshComponent, RING_COMPONENT_NAME)
    ring.set_editor_property("static_mesh", mesh)
    material = unreal.EditorAssetLibrary.load_asset(MATERIAL_PATH)
    if material:
        ring.set_material(0, material)
    rotation, scale = fit_ring_transform(mesh)
    ring.set_editor_property("relative_rotation", rotation)
    ring.set_editor_property("relative_scale3d", scale)
    # Purely decorative: must not push the camera or the player around.
    ring.set_collision_profile_name("NoCollision")
    ring.set_editor_property("mobility", unreal.ComponentMobility.MOVABLE)

    unreal.BlueprintEditorLibrary.compile_blueprint(blueprint)
    unreal.EditorAssetLibrary.save_asset(TORUS_BP_PATH, False)
    return blueprint


def attach_to_character(torus_blueprint):
    character = unreal.EditorAssetLibrary.load_asset(CHARACTER_BP_PATH)
    if not character:
        raise RuntimeError("Could not find {}".format(CHARACTER_BP_PATH))

    torus_class = torus_blueprint.generated_class()
    existing = find_component_handle(
        character,
        lambda component: isinstance(component, unreal.ChildActorComponent)
        and component.get_editor_property("child_actor_class") == torus_class,
    )
    if existing:
        unreal.log("BP_Torus is already attached to the character")
        return

    capsule_handle = find_component_handle(character, lambda component: isinstance(component, unreal.CapsuleComponent))
    if not capsule_handle:
        raise RuntimeError("Could not find the capsule component on the character")

    half_height = 96.0
    character_default = unreal.get_default_object(character.generated_class())
    if character_default and character_default.capsule_component:
        half_height = character_default.capsule_component.get_unscaled_capsule_half_height()

    child = add_component(character, capsule_handle, unreal.ChildActorComponent, CHILD_COMPONENT_NAME)
    child.set_editor_property("child_actor_class", torus_class)
    child.set_editor_property("relative_location", unreal.Vector(0.0, 0.0, half_height + HEAD_CLEARANCE))

    unreal.BlueprintEditorLibrary.compile_blueprint(character)
    unreal.EditorAssetLibrary.save_asset(CHARACTER_BP_PATH, False)


SUBOBJECT_SUBSYSTEM = unreal.get_engine_subsystem(unreal.SubobjectDataSubsystem)

torus_mesh = import_torus_mesh()
torus_blueprint = create_torus_blueprint(torus_mesh)
attach_to_character(torus_blueprint)
unreal.log("BP_Torus created and attached above the player's head")
